import Foundation

/// Токены поиска авто по госномеру. Оба сервиса пускают физлиц и самозанятых:
/// регистрация по email, токен выдаётся сразу, договор не нужен.
///
/// - `avtoVinCodToken` — avtovincod.ru, метод `gos2vin`: VIN, марка, модель,
///   год выпуска, мощность. От 5.5 ₽ за успешный запрос, ненайденное
///   бесплатно, **без месячных платежей**, пополнение картой от 100 ₽.
///   Для физлица с малым объёмом это выгодный вход.
/// - `apiCloudToken` — api-cloud.ru, метод `rsa.php` (ОСАГО): марка+модель и
///   VIN (бывает замаскирован). 0.50 ₽ за успешный запрос, но при объёме до
///   2000 запросов в месяц списывается гарантийный платёж 700 ₽/мес и
///   минимальное пополнение картой 2000 ₽ — для малых объёмов дороже.
///
/// Заполнен AvtoVinCod — работает он; иначе api-cloud; оба пустые — заглушка
/// из макета, как раздел «Карта» без ключа.
///
/// Решение «ключ поставщика — только на сервере» из DECISIONS.md здесь
/// сознательно нарушено по прямой просьбе пользователя: своего сервера нет,
/// а поиск нужен сейчас. Риск прежний — токен вынимается из `.ipa`, и за
/// него могут списать баланс; с появлением сервера запрос обязан переехать
/// туда (docs/BACKEND.md).
enum VehicleLookupKey {
    static let avtoVinCodToken = ""
    static let apiCloudToken = ""

    static var hasAvtoVinCod: Bool { !avtoVinCodToken.isEmpty }
    static var hasAPICloud: Bool { !apiCloudToken.isEmpty }
}
