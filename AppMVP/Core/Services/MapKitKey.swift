/// Ключ MapKit. Получается в кабинете разработчика Яндекс Карт, бесплатен
/// до 25 000 активных пользователей в месяц.
///
/// Ключ лежит прямо в приложении намеренно, и это не противоречит решению
/// «ключ поставщика только на сервере» из журнала: у мобильных SDK карт другая
/// модель — ключ привязан к бандлу `com.vladislavkotyrev.appmvp` и без него
/// бесполезен, поэтому секретом не является. Так же его хранят и сами
/// примеры Яндекса.
///
/// Пока строка пустая, раздел «Карта» показывает объяснение вместо карты,
/// а не пустой экран.
enum MapKitKey {
    /// Вставьте ключ сюда.
    static let value = ""

    static var isConfigured: Bool { !value.isEmpty }
}
