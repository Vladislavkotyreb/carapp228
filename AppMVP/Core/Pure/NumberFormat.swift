import Foundation

/// Числа на экране и числа из полей ввода.
///
/// Обе стороны живут вместе: разбор «12 000 ₽» обязан понимать то, что
/// напечатала `grouped` — включая неразрывный пробел, которым она разделяет
/// разряды.
enum NumberFormat {
    /// Разряды через неразрывный пробел: `9 000 000`.
    ///
    /// Пробел именно неразрывный: число и единица («км», «₽») не должны
    /// разъезжаться по строкам.
    /// Разряды по три и включённая группировка заданы явно, а не оставлены
    /// локали устройства: в макете число разбито по три, и на локали с другой
    /// разрядностью (индийская группирует 2-2-3) экран разошёлся бы с макетом.
    /// Разделитель локаль и так не выбирает — он перебит на неразрывный пробел.
    static func grouped(_ value: Int) -> String {
        let formatter = NumberFormatter()
        formatter.numberStyle = .decimal
        formatter.usesGroupingSeparator = true
        formatter.groupingSize = 3
        formatter.groupingSeparator = "\u{00A0}"
        return formatter.string(from: NSNumber(value: value)) ?? "\(value)"
    }

    /// Целое из того, что напечатал человек: всё, кроме цифр, отбрасывается.
    ///
    /// `nil` означает «цифр нет вовсе» либо «не влезло в `Int`» — вызывающий
    /// сам решает, чем это заменить. Знак минус тоже отбрасывается: ни пробег,
    /// ни сумма отрицательными не бывают.
    static func digits(_ raw: String) -> Int? {
        Int(raw.filter(\.isNumber))
    }

    /// То же с запасным значением на случай пустого или негодного ввода.
    static func digits(_ raw: String, or fallback: Int) -> Int {
        digits(raw) ?? fallback
    }
}
