import Foundation

/// Числа на экране и числа из полей ввода.
///
/// Обе стороны живут вместе: разбор «12 000 ₽» обязан понимать то, что
/// напечатала `grouped` — включая неразрывный пробел, которым она разделяет
/// разряды.
enum NumberFormat {
    /// Разряды через неразрывный пробел: `9 000 000`.
    ///
    /// Пробел именно неразрывный: число и единица («км», «₽») не должны
    /// разъезжаться по строкам.
    /// Разряды по три и включённая группировка заданы явно, а не оставлены
    /// локали устройства: в макете число разбито по три, и на локали с другой
    /// разрядностью (индийская группирует 2-2-3) экран разошёлся бы с макетом.
    /// Разделитель локаль и так не выбирает — он перебит на неразрывный пробел.
    static func grouped(_ value: Int) -> String {
        let formatter = NumberFormatter()
        formatter.numberStyle = .decimal
        formatter.usesGroupingSeparator = true
        formatter.groupingSize = 3
        formatter.groupingSeparator = "\u{00A0}"
        return formatter.string(from: NSNumber(value: value)) ?? "\(value)"
    }

    /// Живая маска числового поля: из ввода остаются цифры, сгруппированные
    /// по три неразрывным пробелом — «1200000» на глазах становится
    /// «1 200 000». Просьба пользователя: большие пробеги без разбивки
    /// приходилось пересчитывать глазами. Обратный разбор — `digits`, он
    /// неразрывный пробел отбрасывает. Девять цифр — потолок: больше не
    /// влезает ни в пробег, ни в цену.
    static func groupedInput(_ raw: String) -> String {
        let onlyDigits = String(raw.filter(\.isNumber).prefix(9))
        guard let value = Int(onlyDigits) else { return "" }
        return grouped(value)
    }

    /// Целое из того, что напечатал человек: всё, кроме цифр, отбрасывается.
    ///
    /// `nil` означает «цифр нет вовсе» либо «не влезло в `Int`» — вызывающий
    /// сам решает, чем это заменить. Знак минус тоже отбрасывается: ни пробег,
    /// ни сумма отрицательными не бывают.
    static func digits(_ raw: String) -> Int? {
        Int(raw.filter(\.isNumber))
    }

    /// То же с запасным значением на случай пустого или негодного ввода.
    static func digits(_ raw: String, or fallback: Int) -> Int {
        digits(raw) ?? fallback
    }
}

/// Телефон места на карте: что показать человеку и куда звонить по нажатию.
///
/// Отдельно от `NumberFormat`, потому что это не число: разряды тут не считают,
/// а разбирают то, что прислал поиск. Правила простые и злые — номер, который
/// не удалось разобрать, лучше не показывать вовсе, чем показать кнопку,
/// которая никуда не звонит.
enum PhoneFormat {
    /// Сколько цифр считаем телефоном. Нижняя граница — короткие номера
    /// сервисов («0890»), верхняя — E.164 с кодом страны.
    static let digitRange = 4...15

    /// Первый годный номер из тех, что отдал поиск.
    ///
    /// Порядок Яндекса сохраняется: первым он отдаёт основной номер
    /// организации, и выбирать из списка «самый красивый» значило бы звонить
    /// в бухгалтерию вместо приёмки.
    static func first(of numbers: [String]) -> String? {
        numbers.first { dial($0) != nil }
    }

    /// Ссылка для звонка: `tel:+74951234567`.
    ///
    /// `nil` — номер разобрать не удалось, и кнопки «Позвонить» быть не должно.
    /// Плюс сохраняется только ведущий: внутри номера он ничего не значит,
    /// а `tel:` с плюсом посередине iOS не откроет.
    static func dial(_ raw: String) -> String? {
        let trimmed = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        let digits = trimmed.filter(\.isNumber)
        guard digitRange.contains(digits.count) else { return nil }
        return trimmed.hasPrefix("+") ? "tel:+" + digits : "tel:" + digits
    }

    /// Что написать на кнопке. Яндекс присылает номер уже набранным по-русски
    /// («+7 (495) 123-45-67»), и переписывать его своими руками незачем —
    /// достаточно убрать лишние пробелы по краям и внутри.
    static func display(_ raw: String) -> String {
        raw.split(whereSeparator: \.isWhitespace).joined(separator: "\u{00A0}")
    }
}
