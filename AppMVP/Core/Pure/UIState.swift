import Foundation

// Типы состояний экранов.
//
// Пока вью их не используют: состояние там разложено по отдельным `@State`
// (в `IssuesScreen` их пять булевых — это 32 сочетания, из которых осмысленны
// восемь). Типы заведены раньше переписывания намеренно: на них держится
// каталог состояний, а каталог — единственный способ увидеть все экраны рядом.
// Перевод вью на эти типы — следующий шаг, и он требует Xcode: без сборки
// такую правку делать вслепую нельзя.
//
// `rawValue` каждого случая уходит в имя PNG и в имя фрейма Figma, поэтому
// они не переименовываются: на них держится замена картинок при переснятии.

/// Что показывает раздел «Ошибки».
enum IssuesPhase: String, CaseIterable {
    /// История пуста — «Слушать» пишет на месте, без модалки.
    case empty
    /// История есть, запись не идёт.
    case history
    /// Запись на пустом экране: модалка не нужна, закрывать нечего.
    case recordingInline
    /// Запись поверх непустого экрана — модалка с притемнением (`46105:3970`).
    case recordingModal
    /// Запись отдана на разбор, ответа ещё нет.
    case analyzing
}

/// Что показывает шторка «Вот что мы нашли».
///
/// Семь исходов, и шесть из них на экране никто не видел: они требуют
/// определённых ответов сервера. Ровно ради таких состояний и нужна галерея.
enum FindingsOutcome: String, CaseIterable {
    /// Сервер не настроен — показываем заглушку, как «Карта» без ключа.
    case stub
    /// Сервер поднят без модели.
    case serverWithoutModel
    /// Привратник CLAP не услышал мотора.
    case notEngine
    /// Вердикт «есть неисправность» — единственный случай, когда показываем версии.
    case fault
    /// Вердикт «норма».
    case normal
    /// Вердикт посередине: судить не берёмся.
    case uncertain
    /// Сеть или разбор отказали.
    case failed
}

/// Экран добавления машины.
enum AddCarPhase: String, CaseIterable {
    /// Вкладка «По номеру», поле пустое.
    case plateEmpty
    /// Номер введён полностью.
    case plateFilled
    /// Идёт поиск по номеру.
    case searching
    /// Шторка «Это ваш автомобиль?» (`45854:2936`).
    case found
    /// Вкладка «По названию», поля пустые.
    case byName
    /// Вкладка «По названию», поля заполнены.
    case byNameFilled
}

/// Ошибка поля на экране добавления. Раньше жила в `AddCarView.swift`;
/// переехала сюда, чтобы каталог состояний мог на неё сослаться, а проверки —
/// пересчитать её случаи.
enum FieldError: String, CaseIterable {
    case plateInvalid
    case plateNotFound
    case detailsMissing
    case lookupFailed

    var message: String {
        switch self {
        case .plateInvalid: return "Введите госномер: буква, 3 цифры, 2 буквы и код региона"
        case .plateNotFound: return "Мы не нашли такого номера в базе, попробуйте другой"
        case .detailsMissing: return "Введите название машины и её пробег"
        case .lookupFailed: return "Не удалось проверить номер, попробуйте позже"
        }
    }
}

/// Страница раздела «Машина».
enum CarPhase: String, CaseIterable {
    /// История ТО пуста — пустое состояние, прокрутки нет.
    case noHistory
    /// Есть история: блоки «ТО через», «Всего потрачено», лента записей.
    case withHistory
    /// Список прокручен: чёрная шапка (`46001:6457`), свайп карусели заперт.
    case scrolled
    /// Последняя страница карусели — «Добавить авто» (`45949:3265`).
    case addPage
    /// Машина без фото.
    case noPhoto
}

/// Шторки добавления ТО.
enum ServiceSheet: String, CaseIterable {
    /// Выбор способа: фото/PDF или вручную (`45883:3842`).
    case choice
    /// Ручной ввод, поля пустые (`45870:2868`).
    case manualEmpty
    /// Ручной ввод, заполнено несколько работ.
    case manualFilled
    /// Правка существующей записи.
    case editing
    /// Форма, заполненная разбором фото/PDF (сейчас заглушка).
    case parsed
}

/// Шаги онбординга.
enum OnboardingStep: String, CaseIterable {
    case welcome
    case survey1
    case survey2
    case survey3
}

/// Раздел «Карта».
enum MapPhase: String, CaseIterable {
    /// Ключ MapKit не задан — раздел объясняет это вместо пустого экрана.
    case noKey
    /// Карта с позицией пользователя.
    case live
}

/// Таббар.
enum TabBarPhase: String, CaseIterable {
    case expanded
    case minimized
}
