/// Какая модалка раздела «Машина» открыта. Слот один, потому что их
/// и не бывает две сразу.
///
/// Раньше это были пять независимых булевых, то есть 32 сочетания, из которых
/// законно шесть. Две открытые шторки — не абстрактная опасность: в этом файле
/// уже ловили, как общий пикер фото открывал чужую модалку.
///
/// Случай называется `closed`, а не `none`: `none` в местах, где ждут
/// `Optional`, читается двусмысленно.
///
/// Что сюда **не** входит: тост (он не модалка и живёт поверх), скрытие
/// таббара (им управляет раздел «Ошибки») и `editingRecord` — это данные
/// о том, что правят, а не то, какое окно открыто.
enum CarSheet: String, CaseIterable {
    case closed
    /// Выбор способа добавления ТО: фото/PDF или вручную.
    case serviceChoice
    /// Форма ТО — добавление или правка, это решает `editingRecord`.
    case service
    /// Шторка «Добавить авто».
    case addCar
    /// Пейвол подписки «Beepy Плюс» — «Добавить авто» сверх двух машин
    /// (`Garage.decide`).
    case paywall
    /// Шторка «Это ваш автомобиль?» после поиска по номеру (`45854:2936`) —
    /// тот же шаг подтверждения, что и на первом входе: без него машина
    /// добавлялась молча, и было непонятно, что нашлось и нашлось ли.
    case carFound
    /// Выбор источника документа ТО: галерея или файл PDF.
    case docSource
    /// Системный пикер фото.
    case photoPicker
    /// Системный выбор файла (PDF или скан из «Файлов»).
    case filePicker
    /// Подтверждение удаления машины.
    case deleteConfirm
    /// Шторка цены: крупная цена, объяснение средней по рынку, карандаш
    /// правки. Открывается тапом по плитке «Цена авто».
    case priceInfo
    /// Та же шторка для пробега — тапом по плитке «Пробег».
    case odometerInfo
    /// «Что расскажем сервису» — сводка перед картой по «Записаться».
    case booking
    /// Быстрое прослушивание — системная шторка на пол-экрана с пузырём.
    case listening
    /// «Вот что мы нашли» после быстрого прослушивания.
    case findings
    /// Сохранённое прослушивание из ленты истории: что тогда нашли. Какое
    /// именно — данные рядом (`viewingCheck`), как у `editingRecord`.
    case checkDetail
    /// Поездка из ленты «Поездки»: экран с картой. Какая именно — данные
    /// рядом (`viewingTrip`); то же у двух случаев ниже.
    case tripDetail
    /// Подтверждение удаления поездки — после свайпа по карточке.
    case tripDelete
    /// Правка расстояния поездки — после свайпа по карточке.
    case tripDistance
}

