/// Что показывает раздел «Карта»: карту или список мест поверх неё.
///
/// Переключается кнопкой «Список / Карта» справа внизу, по образцу Upside
/// (выбор пользователя 03.10.2026). До этого значение побывало сегментом
/// «Карта / Список» наверху и положением выдвижной шторки; смысл всё это
/// время один — что сейчас главное на экране. Одно значение вместо булева
/// `isListShown`: подача есть измерение с именем, и фаза раздела выводится
/// из него.
enum MapMode: String, CaseIterable, Identifiable {
    /// Карта во весь экран: сверху поиск и чипы, внизу — карточка выбранного
    /// места или булавки, когда они есть.
    case map
    /// Список мест от ближнего к дальнему под теми же поиском и чипами.
    case list

    var id: String { rawValue }
}

/// Раздел «Карта».
enum MapPhase: String, CaseIterable {
    /// Ключ MapKit не задан — раздел объясняет это вместо пустого экрана.
    case noKey
    /// Карта с позицией пользователя.
    case live
    /// Список мест: свои точки и найденное рядом.
    case list
    /// Список, в котором нечего показать: ничего не нашлось и не сохранено.
    case listEmpty

    /// Фаза выводится из подачи, наличия ключа и наличия мест.
    ///
    /// Ключ старше подачи: без него не работает ни карта, ни поиск, и список
    /// был бы пустым не потому, что мест нет, а потому, что их неоткуда взять.
    static func of(mode: MapMode, hasKey: Bool, hasPlaces: Bool) -> MapPhase {
        guard hasKey else { return .noKey }
        switch mode {
        case .map: return .live
        case .list: return hasPlaces ? .list : .listEmpty
        }
    }
}

/// Карточка места на карте. Открывается над точкой, в месте тапа, а не
/// шторкой снизу (образец пользователя, 21.10.2026); тап по карточке
/// переворачивает её.
enum MapCardFace: String, CaseIterable {
    /// Лицо: фото, название, адрес, оценка и расстояние.
    case front
    /// Оборот: рубрики из списка, фото лентой и действия — маршрут, звонок,
    /// запись, сайт.
    case back

    var flipped: MapCardFace { self == .front ? .back : .front }
}

