import Foundation

// Типы состояний экранов.
//
// Пока вью их не используют: состояние там разложено по отдельным `@State`
// (в `IssuesScreen` их пять булевых — это 32 сочетания, из которых осмысленны
// восемь). Типы заведены раньше переписывания намеренно: на них держится
// каталог состояний, а каталог — единственный способ увидеть все экраны рядом.
// Перевод вью на эти типы — следующий шаг, и он требует Xcode: без сборки
// такую правку делать вслепую нельзя.
//
// `rawValue` каждого случая уходит в имя PNG и в имя фрейма Figma, поэтому
// они не переименовываются: на них держится замена картинок при переснятии.

/// Что раздел «Ошибки» сейчас делает.
///
/// Одно значение вместо двух булевых. «Записываю» и «разбираю» одновременно —
/// состояние, которого не бывает, и теперь его **нельзя выразить**: тест для
/// этого не нужен, багу негде жить.
///
/// Это измерение — деятельность. Второе, независимое, — есть ли история;
/// оно приходит из данных, а не отсюда. Мешать их в одном типе нельзя:
/// история остаётся, пока идёт запись, и меняется без участия деятельности.
enum IssuesActivity: String, CaseIterable {
    /// Ничего не делаем: экран в покое, шторка может быть открыта.
    case idle
    /// Идёт запись звука.
    case recording
    /// Запись отдана на разбор, ответа ещё нет.
    case analyzing
}

/// Что показывает раздел «Ошибки».
enum IssuesPhase: String, CaseIterable {
    /// История пуста — «Слушать» пишет на месте, без модалки.
    case empty
    /// История есть, запись не идёт.
    case history
    /// Запись на пустом экране: модалка не нужна, закрывать нечего.
    case recordingInline
    /// Запись поверх непустого экрана — модалка с притемнением (`46105:3970`).
    case recordingModal
    /// Запись отдана на разбор, ответа ещё нет.
    case analyzing

    /// Фаза выводится из деятельности и наличия истории — двух измерений,
    /// которые не смешиваются. Функция чистая, поэтому проверяется целиком:
    /// шесть сочетаний на пять фаз, и каждая фаза обязана быть достижимой.
    static func of(activity: IssuesActivity, hasHistory: Bool) -> IssuesPhase {
        switch activity {
        case .analyzing:
            // Разбор идёт поверх любого экрана и выглядит одинаково:
            // кнопка держит индикатор, остальное не меняется.
            return .analyzing
        case .recording:
            // Модалка нужна, только когда под ней есть что притемнять.
            return hasHistory ? .recordingModal : .recordingInline
        case .idle:
            return hasHistory ? .history : .empty
        }
    }
}

/// Что показывает шторка «Вот что мы нашли».
///
/// Семь исходов, и шесть из них на экране никто не видел: они требуют
/// определённых ответов сервера. Ровно ради таких состояний и нужна галерея.
/// Находки показывают два — `stub` и `fault`; остальные пять — пустое
/// состояние шторки, см. `FindingsEmpty`.
enum FindingsOutcome: String, CaseIterable {
    /// Сервер не настроен — показываем заглушку, как «Карта» без ключа.
    case stub
    /// Сервер поднят без модели.
    case serverWithoutModel
    /// Привратник CLAP не услышал мотора.
    case notEngine
    /// Вердикт «есть неисправность» — единственный случай, когда показываем версии.
    case fault
    /// Вердикт «норма».
    case normal
    /// Вердикт посередине: судить не берёмся.
    case uncertain
    /// Сеть или разбор отказали.
    case failed
}

/// Пустое состояние шторки находок: показывать нечего — неисправностей не
/// названо, мотора не слышно или разбор не удался.
///
/// Отдельный тип, а не карточка в списке находок (решение пользователя
/// 04.10.2026): карточка «ничего не слышно» стояла под вопросом «Прикрепить
/// к машине?» и над кнопкой «Да, добавить ошибки» — шторка предлагала
/// сохранить в историю то, чего не нашли. В пустом состоянии прикреплять
/// нечего, и ответов два: «Ещё раз» и «Закрыть».
enum FindingsEmpty: Equatable {
    /// Вердикт «норма»: тревожного не слышно.
    case nothingFound
    /// Вердикт посередине: по этой записи судить не берёмся.
    case unsure
    /// Привратник не услышал мотора; что делать — словами.
    case notEngine(explanation: String)
    /// Разбор не удался; причина — словами.
    case failed(reason: String)

    var title: String {
        switch self {
        case .nothingFound: "Мы ничего не\u{00A0}нашли"
        case .unsure: "По этой записи судить не\u{00A0}берёмся"
        case .notEngine: "Двигателя не\u{00A0}слышно"
        case .failed: "Не\u{00A0}удалось разобрать запись"
        }
    }

    var message: String {
        switch self {
        case .nothingFound:
            "Попробуйте ещё раз или порадуйтесь за\u{00A0}себя и\u{00A0}свою машину"
        case .unsure:
            // «Порадуйтесь» здесь было бы неправдой: разбор не сказал «норма».
            "Запишите ещё раз, ближе к\u{00A0}мотору"
        case .notEngine(let explanation):
            explanation
        case .failed(let reason):
            "\(reason). Запись не\u{00A0}сохранена — попробуйте ещё\u{00A0}раз"
        }
    }

    /// Пустое состояние по ответу разбора или `nil`, если есть что показать.
    ///
    /// Порядок вопросов — порядок доверия: без модели ответу верить нельзя
    /// вовсе; дальше привратник «это вообще мотор?»; и только потом вердикт.
    /// Находки показываем **только** при вердикте «неисправность»: голова
    /// причин раскладывает свои 100 % по деталям при любом входе, и на
    /// тишине уверенно называла выхлоп.
    static func of(modelLoaded: Bool, isEngine: Bool, verdict: String,
                   heardExplanation: String) -> FindingsEmpty? {
        guard modelLoaded else { return .failed(reason: "Сервер запущен без модели") }
        guard isEngine else { return .notEngine(explanation: heardExplanation) }
        switch verdict {
        case "fault": return nil
        case "normal": return .nothingFound
        default: return .unsure
        }
    }

    /// Значок состояния. Галочка — только там, где разбор сказал «норма».
    var symbol: String {
        switch self {
        case .nothingFound: "checkmark.seal"
        case .unsure: "questionmark.circle"
        case .notEngine: "waveform.badge.exclamationmark"
        case .failed: "exclamationmark.triangle"
        }
    }
}

