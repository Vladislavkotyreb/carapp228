/// Раздел документа: заголовок и абзацы.
struct LegalSection: Identifiable, Equatable {
    let title: String
    let blocks: [LegalBlock]

    var id: String { title }

    init(_ title: String, _ blocks: [LegalBlock]) {
        self.title = title
        self.blocks = blocks
    }
}

/// Абзац или пункт списка. У пункта начало выделено: «Поиск машины по
/// госномеру.» — так список читается по первым словам.
enum LegalBlock: Equatable {
    case text(String)
    case item(String, String)
}

/// Как связаться с разработчиком: «Связаться» на корне «Ещё» и строка
/// оператора в политике. Пользователь разрешил показывать оба адреса
/// (23.10.2026, те же, что в README).
