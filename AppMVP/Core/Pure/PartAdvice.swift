    /// Что обычно меняют. Список расходников, а не работ: то, что можно
    /// заранее посмотреть по цене и не ехать в сервис вслепую.
    static func parts(_ part: String) -> [String] {
        switch part {
        case "engine_internal", "rod_knock":
            ["Масло моторное", "Масляный фильтр"]
        case "valvetrain":
            ["Масло моторное", "Гидрокомпенсаторы", "Прокладка клапанной крышки"]
        case "low_oil":
