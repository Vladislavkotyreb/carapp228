    /// как «купите всё это», чего разбор со своей точностью обещать не может.
    static func line(_ part: String) -> String? {
        let items = parts(part).prefix(2).joined(separator: ", ")
        switch (check(part), items.isEmpty) {
        case (let text?, true):  return text
        case (let text?, false): return text + ". Обычно меняют: " + items
        case (nil, false):       return "Обычно меняют: " + items
        case (nil, true):        return nil
        }
    }
