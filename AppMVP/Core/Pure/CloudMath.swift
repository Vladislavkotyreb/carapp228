import Foundation

/// Облачко прослушивания: стеклянная пилюля с лентой света.
///
/// Здесь то, что решается без SwiftUI: форма пилюли и дыхание в тишине.
/// Рисует шейдер `cloudOrb`, числа в него отдаёт `SoundCapsule`.
enum CloudMath {
    /// Кадр облачка — как у шара в макете (370 × 238.955), чтобы оно встало
    /// на его место без правок вёрстки.
    static let aspect: Double = 1.55

    /// Сама пилюля внутри кадра: 0.74 его ширины и в 1.4 раза шире своей
    /// высоты — размер и пропорция пузыря на растре макета (274 × 196 pt).
    static let pillWidth: Double = 0.74
    static let pillAspect: Double = 1.4

    /// Показатель суперэллипса: 2 — эллипс, чем больше, тем ближе к
    /// прямоугольнику. 3.4 читался коробкой («фара», 06.10.2026); 2.5 даёт
    /// плоские верх и низ и круглые торцы, как на записи экрана.
    static let squircle: Double = 2.5

    /// Уровень, которым живёт облачко: в тишине дышит само между 0.22 и 0.38,
    /// с голосом мотора идёт за ним. Мёртвая картинка на экране прослушивания
    /// читается как сломанная.
    static func drive(level: Double, at time: Double) -> Double {
        let breath = (0.6 * sin(time * 1.3) + 0.4 * sin(time * 3.1 + 1.2) + 1) / 2
        let idle = 0.22 + 0.16 * breath
        return max(idle, min(1, level))
    }
}
