#!/usr/bin/env bash
# Переносит заметки из хранилища Obsidian в inbox/ репозитория и обратно.
#
# Зачем. Утренний разбор идёт в облаке, а облако видит только GitHub — телефона
# оно не видит. Клонировать сам репозиторий в Obsidian на iPhone нельзя: 85 МБ
# истории и 71 МБ картинок в AppMVP, плагин Git на мобиле это не вывезет.
# Поэтому доставкой занимается мак, где хранилище и так лежит после
# синхронизации с телефоном.
#
# Источник правды — репозиторий. Хранилище получает его зеркалом, включая
# done/ и reports/: иначе разобранная заметка вернулась бы из хранилища
# обратно в очередь и разбиралась каждое утро заново.
#
# Установка — раз:
#   chmod +x tools/inbox-sync.sh
#   cp tools/dev.beepy.inbox-sync.plist ~/Library/LaunchAgents/
#   launchctl load ~/Library/LaunchAgents/dev.beepy.inbox-sync.plist
#
# Разовый прогон руками: tools/inbox-sync.sh
set -euo pipefail

# --- Заполнить под себя ------------------------------------------------------
# Папка репозитория.
REPO="$HOME/Desktop/ios-app"

# Папка Whelly внутри хранилища Obsidian. Узнать точный путь проще всего так:
# перетащить папку из Finder в Терминал — он подставит её сам.
#
# Двоеточие в имени хранилища не опечатка: Finder показывает «тестовая
# мобила/мак», а на диске это «тестовая мобила:мак» — слэш в имени файла
# macOS не разрешает и подменяет его двоеточием при показе. Путь обязан
# начинаться со слэша: rsync считает удалённым адресом то, где двоеточие
# встретилось раньше первого слэша, и «хранилище:мак/Whelly» он попытался бы
# открыть по ssh.
VAULT="$HOME/Library/Mobile Documents/iCloud~md~obsidian/Documents/тестовая мобила:мак/Whelly"

# Ветка, в которую уезжают заметки.
BRANCH="claude/epic-darwin-axs48i"
# -----------------------------------------------------------------------------

log() { printf '%s  %s\n' "$(date '+%F %T')" "$*"; }

[[ -d "$REPO/.git" ]] || { log "нет репозитория: $REPO"; exit 1; }

# Перетаскивание папки из Finder вставляет путь с экранированием
# («Mobile\ Documents»), а внутри кавычек обратный слэш перестаёт быть
# экранированием и становится обычным символом — папка не находится.
if [[ ! -d "$VAULT" && -d "${VAULT//\\/}" ]]; then
  VAULT="${VAULT//\\/}"
  log "в пути были обратные слэши от Finder — снял"
fi

if [[ ! -d "$VAULT" ]]; then
  log "нет папки хранилища: $VAULT"
  log "Проверить три вещи:"
  log "  1. внутри кавычек не должно быть обратных слэшей — пробелы как есть;"
  log "  2. путь должен кончаться на папку с заметками (…/Whelly), а не на корень хранилища;"
  log "  3. хранилище может лежать не в iCloud — найди папку в Finder и перетащи в Терминал."
  exit 1
fi
cd "$REPO"

# Незакоммиченные правки в коде — не наше дело, но и коммитить их скопом нельзя:
# ниже добавляется только inbox/, явным путём.
git fetch origin "$BRANCH" --quiet
git checkout "$BRANCH" --quiet
git pull --rebase origin "$BRANCH" --quiet || { log "pull не прошёл, чиню руками"; exit 1; }

mkdir -p inbox/tasks inbox/bugs inbox/done inbox/reports inbox/attachments

# 1. Хранилище → репозиторий. Без --delete: удалять заметки может только
#    разбор, переносом в done/. Пропавший в хранилище файл — чаще промах
#    пальцем по экрану, чем решение.
rsync -a --exclude '.obsidian' --exclude '.DS_Store' --exclude '.trash' \
      "$VAULT/" inbox/

# 2. Строки с галочкой из заметок — в отдельные задачи. Без этого шага разбор
#    видит только заметки формата «одна задача — один файл», а с телефона
#    пишутся обычные списки.
python3 tools/inbox-extract.py

if ! git diff --quiet -- inbox || [[ -n "$(git status --porcelain inbox)" ]]; then
  git add inbox
  git commit -q -m "inbox: заметки из Obsidian, $(date '+%F %H:%M')" \
    -m "Перенесено tools/inbox-sync.sh с мака: облачный разбор видит только GitHub."
  git push -q origin "$BRANCH"
  log "отправлено в $BRANCH"
else
  log "новых заметок нет"
fi

# 3. Репозиторий → хранилище, зеркалом. Здесь --delete нужен: разобранная
#    заметка уехала в done/, и её копия в tasks/ обязана исчезнуть, иначе
#    завтрашний разбор возьмёт её снова.
rsync -a --delete --exclude '.obsidian' --exclude '.DS_Store' --exclude '.trash' \
      inbox/ "$VAULT/"
log "хранилище обновлено"
