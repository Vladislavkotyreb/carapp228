#!/usr/bin/env bash
# Переносит заметки из хранилища Obsidian в inbox/ репозитория и обратно.
#
# Зачем. Утренний разбор идёт в облаке, а облако видит только GitHub — телефона
# оно не видит. Клонировать сам репозиторий в Obsidian на iPhone нельзя: 85 МБ
# истории и 71 МБ картинок в AppMVP, плагин Git на мобиле это не вывезет.
# Поэтому доставкой занимается мак, где хранилище и так лежит после
# синхронизации с телефоном.
#
# Источник правды — репозиторий. Хранилище получает его зеркалом, включая
# done/ и reports/: иначе разобранная заметка вернулась бы из хранилища
# обратно в очередь и разбиралась каждое утро заново.
#
# Установка — раз:
#   chmod +x tools/inbox-sync.sh
#   cp tools/dev.canary.inbox-sync.plist ~/Library/LaunchAgents/
#   launchctl load ~/Library/LaunchAgents/dev.canary.inbox-sync.plist
#
# Разовый прогон руками: tools/inbox-sync.sh
set -euo pipefail

# --- Настройка ---------------------------------------------------------------
# Править этот файл не нужно. Путь к папке с заметками передаётся один раз
# аргументом, скрипт запоминает его в ~/.config/canary/vault и дальше берёт
# оттуда — launchd запускает без аргументов.
#
#   tools/inbox-sync.sh "/путь/к/хранилищу/Whelly"   # первый раз
#   tools/inbox-sync.sh                              # потом
#
# Так путь не попадает в текст скрипта, и его нельзя сломать редактором:
# TextEdit подменяет прямые кавычки «умными», и bash перестаёт видеть строку.

# Папка репозитория — там, где лежит сам скрипт, а не там, откуда его запустили.
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

CONFIG="$HOME/.config/canary/vault"
# Путь запоминался под прежним именем приложения. Читаем старый файл, если
# нового ещё нет, но пишем всегда в новый — так настройка переезжает сама
# и не теряется. Без этого переименование молча стёрло бы путь, и утренняя
# синхронизация встала бы с «путь не задан».
LEGACY_CONFIG="$HOME/.config/beepy/vault"

VAULT="${1:-${CANARY_VAULT:-}}"
if [[ -z "$VAULT" ]]; then
  if   [[ -f "$CONFIG"        ]]; then VAULT="$(cat "$CONFIG")"
  elif [[ -f "$LEGACY_CONFIG" ]]; then VAULT="$(cat "$LEGACY_CONFIG")"
  fi
fi

# Ветка, в которую уезжают заметки.
BRANCH="${CANARY_BRANCH:-claude/epic-darwin-axs48i}"
# -----------------------------------------------------------------------------

log() { printf '%s  %s\n' "$(date '+%F %T')" "$*"; }

[[ -d "$REPO/.git" ]] || { log "нет репозитория: $REPO"; exit 1; }

if [[ -z "$VAULT" ]]; then
  log "путь к папке с заметками не задан."
  log "Передай его один раз аргументом — скрипт запомнит:"
  log "  tools/inbox-sync.sh \"/путь/к/хранилищу/Whelly\""
  log "Путь проще всего получить, перетащив папку из Finder в Терминал."
  exit 1
fi

# Перетаскивание папки из Finder вставляет путь с экранированием
# («Mobile\ Documents»), а внутри кавычек обратный слэш перестаёт быть
# экранированием и становится обычным символом — папка не находится.
if [[ ! -d "$VAULT" && -d "${VAULT//\\/}" ]]; then
  VAULT="${VAULT//\\/}"
  log "в пути были обратные слэши от Finder — снял"
fi

if [[ ! -d "$VAULT" ]]; then
  log "нет папки хранилища: $VAULT"
  log "Проверить три вещи:"
  log "  1. внутри кавычек не должно быть обратных слэшей — пробелы как есть;"
  log "  2. путь должен кончаться на папку с заметками (…/Whelly), а не на корень хранилища;"
  log "  3. хранилище может лежать не в iCloud — найди папку в Finder и перетащи в Терминал."
  exit 1
fi
mkdir -p "$(dirname "$CONFIG")"
printf '%s\n' "$VAULT" > "$CONFIG"

cd "$REPO"

# Незакоммиченные правки в коде — не наше дело, но и коммитить их скопом нельзя:
# ниже добавляется только inbox/, явным путём. Отсюда --autostash: без него
# любая недописанная правка в рабочей копии останавливает синхронизацию заметок,
# хотя к заметкам отношения не имеет. autostash прячет её на время перебазирования
# и возвращает обратно — рабочая копия остаётся как была.
git fetch origin "$BRANCH" --quiet

if ! git checkout "$BRANCH" --quiet 2>/dev/null; then
  log "не удалось перейти на $BRANCH — мешают правки в рабочей копии:"
  git status --short | head -20
  exit 1
fi

if ! git pull --rebase --autostash origin "$BRANCH" --quiet; then
  log "pull не прошёл. Состояние рабочей копии:"
  git status --short | head -20
  log "Разобрать вручную: git rebase --abort, затем git stash list."
  exit 1
fi

mkdir -p inbox/tasks inbox/bugs inbox/done inbox/reports inbox/attachments

# Папки, которые ведёт разбор, а не человек. Хранилище получает их зеркалом
# с --delete, и делать это надо ДО импорта: иначе заметка, которую разбор
# перенёс в done/, приезжает из хранилища обратно в tasks/ и разбирается
# каждое утро заново. Ровно это и вылезло на первом сквозном тесте.
MANAGED=(tasks bugs done reports)

mirror_managed() {
  local d
  for d in "${MANAGED[@]}"; do
    mkdir -p "$VAULT/$d"
    rsync -a --delete --exclude '.DS_Store' "inbox/$d/" "$VAULT/$d/"
  done
}

# Папка для того, что должно остаться на маке. Из хранилища не копируется
# вовсе, поэтому в репозиторий не попадает ни при каком раскладе, а репозиторий
# публичный. В .gitignore она тоже есть — на случай ручного `git add -A`.
LOCAL_DIR="Личное"

if [[ ! -d "$VAULT/$LOCAL_DIR" ]]; then
  mkdir -p "$VAULT/$LOCAL_DIR"
  cat > "$VAULT/$LOCAL_DIR/Черновик.md" <<'NOTE'
# Черновик

Всё в папке «Личное» остаётся на маке: синхронизация её не копирует,
в репозиторий она не уезжает, разбор её не видит.

Сюда — мысли, пароли от стендов, недодуманное, ругань. Задачи для приложения —
в «Таски.md».
NOTE
  log "заведена папка $LOCAL_DIR — она остаётся на маке"
fi

# 1. Сначала — состояние разбора в хранилище.
mirror_managed

# 2. Хранилище → репозиторий: заметки человека. Папки разбора исключены, они
#    только что синхронизированы. Без --delete: удалять заметки может только
#    разбор, переносом в done/, а пропавший в хранилище файл — чаще промах
#    пальцем по экрану, чем решение.
rsync -a --exclude '.obsidian' --exclude '.DS_Store' --exclude '.trash' \
      --exclude 'tasks/' --exclude 'bugs/' --exclude 'done/' --exclude 'reports/' \
      --exclude "$LOCAL_DIR/" \
      "$VAULT/" inbox/

# 3. Строки с галочкой из заметок — в отдельные задачи. Без этого шага разбор
#    видит только заметки формата «одна задача — один файл», а с телефона
#    пишутся обычные списки.
python3 tools/inbox-extract.py

if [[ -n "$(git status --porcelain inbox)" ]]; then
  git add inbox
  git commit -q -m "inbox: заметки из Obsidian, $(date '+%F %H:%M')" \
    -m "Перенесено tools/inbox-sync.sh с мака: облачный разбор видит только GitHub."
  git push -q origin "$BRANCH"
  log "отправлено в $BRANCH"
else
  log "новых заметок нет"
fi

# 4. Заведённые задачи и отчёты — обратно в хранилище, чтобы были на телефоне.
mirror_managed

# 5. Заметки, заведённые не с телефона (README, «Мои задачи»), — туда же.
#    --update: если та же заметка в хранилище новее, она остаётся. Иначе правка,
#    сделанная с телефона между синхронизациями, затиралась бы копией из
#    репозитория. --delete здесь нет вовсе: чужие заметки не наше дело.
for f in inbox/*.md; do
  [[ -e "$f" ]] || continue
  rsync -a --update "$f" "$VAULT/"
done

log "хранилище обновлено"
